import Fastify from 'fastify';
import jwt from '@fastify/jwt';
import cors from '@fastify/cors';
import type { Db } from './db.ts';
import { registerAuth } from './auth.ts';
import { registerErrors } from './http.ts';
import { registerSync } from './sync.ts';
import { registerTenancy } from './tenancy.ts';
import { registerUploads } from './uploads.ts';
import { registerJobRoutes } from './routes/jobs.ts';
import { registerFieldRoutes } from './routes/field.ts';
import { registerOfficeRoutes } from './routes/office.ts';
import { registerControlRoutes } from './routes/control.ts';
import { registerQueryRoutes } from './routes/queries.ts';
import { registerDocumentRoutes } from './routes/documents.ts';
import { registerPastelRoutes } from './routes/pastel.ts';
import { registerPastelSetupRoutes } from './routes/pastelSetup.ts';
import { registerPayRoutes } from './routes/pay.ts';
import { registerSupplierInvoiceRoutes } from './routes/supplierInvoices.ts';
import { registerClientRateRoutes } from './routes/clientRates.ts';
import { registerDebtorRoutes } from './routes/debtors.ts';
import { registerProfitRoutes } from './routes/profit.ts';
import { registerPurchaseOrderRoutes } from './routes/purchaseOrders.ts';
import { registerWhoRoutes } from './routes/who.ts';
import { registerClientRoutes } from './routes/clients.ts';
import { registerSearchRoutes } from './routes/search.ts';
import { registerSetupRoutes } from './routes/setup.ts';
import { registerStockTakeRoutes } from './routes/stockTake.ts';
import { registerStockOrderRoutes } from './routes/stockOrders.ts';
import { registerPeopleRoutes, registerTerminationRoutes } from './routes/people.ts';
import { registerLoginRoutes } from './routes/logins.ts';
import { registerStaffRoutes } from './routes/staff.ts';
import { registerDepartmentRoutes } from './routes/departments.ts';
import { registerTimesheetRoutes } from './routes/timesheets.ts';
import { registerMenuRoutes } from './routes/menus.ts';
import { registerAccessRoutes } from './routes/access.ts';
import { registerPlatformRoutes } from './routes/platform.ts';
import { registerStockRoutes } from './routes/stock.ts';
import { registerFleetRoutes } from './routes/fleet.ts';
import { registerVehicleRoutes } from './routes/vehicles.ts';
import { registerWorkshopRoutes } from './routes/workshop.ts';
import type { InvoiceReader } from './invoiceReader.ts';
import { mailerFromEnv, type Mailer } from './mailer.ts';
import { registerReportRoutes } from './routes/reports.ts';
import { registerRepairRoutes } from './routes/repairs.ts';
import { registerToolStoreRoutes } from './routes/toolStore.ts';
import { registerBreakdownRoutes, type IntakeOptions } from './routes/breakdowns.ts';
import { registerWhatsAppRoutes } from './routes/whatsapp.ts';
import type { Fetch, MetaConfig } from './whatsapp.ts';
import { registerCustomerImportRoutes } from './routes/customers.ts';
import { breakdownReaderFromEnv } from './breakdownReader.ts';

/** db must connect as the app's own database role (no superuser, no row-level-security bypass). */
export async function buildApp(db: Db, opts: { jwtSecret: string; logger?: boolean; corsOrigins?: string[]; invoiceReader?: InvoiceReader | null; mailer?: Mailer | null; intake?: Partial<IntakeOptions>; whatsapp?: { fetch?: Fetch; meta?: MetaConfig | null } }) {
  if (!opts.jwtSecret || opts.jwtSecret.length < 32) throw new Error('JWT secret must be at least 32 characters');
  const app = Fastify({ logger: opts.logger ?? false, bodyLimit: 1_000_000, trustProxy: true });
  registerErrors(app);
  await app.register(cors, { origin: opts.corsOrigins ?? false });
  await app.register(jwt, { secret: opts.jwtSecret });
  await registerUploads(app);
  app.get('/health', async () => ({ ok: true }));
  registerTenancy(app);
  registerAuth(app, db);
  registerSync(app);
  registerJobRoutes(app, db);
  registerFieldRoutes(app, db);
  registerOfficeRoutes(app, db);
  registerControlRoutes(app);
  registerQueryRoutes(app);
  registerDocumentRoutes(app);
  registerPastelRoutes(app);
  registerPastelSetupRoutes(app);
  registerPayRoutes(app);
  registerClientRateRoutes(app);
  registerDebtorRoutes(app);
  registerProfitRoutes(app);
  registerPurchaseOrderRoutes(app, opts.intake?.poReader);
  registerWhoRoutes(app);
  registerClientRoutes(app, opts.mailer === undefined ? mailerFromEnv() : opts.mailer);
  registerSearchRoutes(app);
  registerSetupRoutes(app);
  registerStockTakeRoutes(app);
  registerStockOrderRoutes(app, opts.mailer === undefined ? mailerFromEnv() : opts.mailer);
  registerTerminationRoutes(app);
  registerPeopleRoutes(app);
  registerLoginRoutes(app);
  registerCustomerImportRoutes(app);
  registerBreakdownRoutes(app, db, { reader: breakdownReaderFromEnv(), ...opts.intake });
  registerWhatsAppRoutes(app, db, { reader: opts.intake?.reader ?? breakdownReaderFromEnv(), bridgeKey: opts.intake?.bridgeKey, ...opts.whatsapp });
  registerStaffRoutes(app);
  registerDepartmentRoutes(app);
  registerTimesheetRoutes(app);
  registerMenuRoutes(app);
  registerReportRoutes(app, opts.mailer === undefined ? mailerFromEnv() : opts.mailer);
  registerRepairRoutes(app);
  registerToolStoreRoutes(app);
  registerAccessRoutes(app, db);
  registerPlatformRoutes(app, db);
  registerStockRoutes(app, db, opts.invoiceReader ?? null);
  registerSupplierInvoiceRoutes(app, db, opts.invoiceReader ?? null);
  registerFleetRoutes(app, db);
  registerVehicleRoutes(app);
  registerWorkshopRoutes(app);
  return app;
}
